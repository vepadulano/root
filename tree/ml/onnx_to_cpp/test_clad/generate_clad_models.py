"""Generator for the ONNX models of the tests of the differentiation of the code
generated by ONNXToCpp with Clad, and for the data of their inputs and outputs.

The models and the way to build their references are the same as the ones of
the tests of the generated code. The expected outputs are computed with onnx's
ReferenceEvaluator and written to references/<Name>.ref in the output
directory, from where the tests read both the inputs and the expected outputs.

    python3 generate_clad_models.py --outdir <dir>
"""

